// Concatenate migrations + seed into supabase/setup.sql for pasting into the
// Supabase SQL Editor (for setups without the Supabase CLI).
import fs from "node:fs";
const dir = "supabase/migrations";
const parts = fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()
  .map((f) => `-- ===== ${f} =====\n${fs.readFileSync(`${dir}/${f}`, "utf8")}`);
parts.push(`-- ===== seed.sql =====\n${fs.readFileSync("supabase/seed.sql", "utf8")}`);
fs.writeFileSync("supabase/setup.sql", `-- GENERATED by scripts/bundle-sql.mjs. Do not edit; edit the migrations instead.\n-- Run once on a fresh Supabase project (SQL Editor → New query → paste → Run).\n\n${parts.join("\n\n")}\n`);
console.log("wrote supabase/setup.sql");
